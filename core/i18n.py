def t(key: str, **kwargs) -> str:
    lang = _LANG[0]
    val = _T.get(lang, _T["vi"]).get(key) or _T["vi"].get(key, key)
    return val.format(**kwargs) if kwargs else val


def set_lang(lang: str):
    if lang in _T:
        _LANG[0] = lang


def get_lang() -> str:
    return _LANG[0]


def weekdays() -> list:
    return WEEKDAYS.get(_LANG[0], WEEKDAYS["vi"])


def months() -> list:
    return MONTHS.get(_LANG[0], MONTHS["vi"])


def greeting(hour: int) -> str:
    if hour < 12:
        return t("good_morning")
    elif hour < 18:
        return t("good_afternoon")
    return t("good_evening")


def stt_code() -> str:
    return STT_CODES.get(_LANG[0], "vi-VN")


def tts_code() -> str:
    return TTS_CODES.get(_LANG[0], "vi")


def ai_lang_instruction() -> str:
    return _T.get(_LANG[0], _T["vi"]).get("ai_lang_instruction", "")
